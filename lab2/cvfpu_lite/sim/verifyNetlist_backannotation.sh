#!/bin/bash
#clear log file and file for store all tb_results
#>../log/log_verifyNet.txt
>all_tb_results.txt
>tb_results.txt

#while to verify each netlist generated in the directory 'netlist'
ls ../netlist/ | grep .v | while read -r line
do

rm -r work 2>/dev/null

net=${line%.v}
echo "verifying " $net 
>tb_results.txt
echo "..." >> all_tb_results.txt

#change clock period into a clock_gen.vhd to verify the correct functionality of the netlist
#clock period is in the file clock_period.txt 
CLK_PERIOD=$(cat ../clock_period.txt | grep -w $net | cut -d ' ' -f 2)
sed -i -E "s/(constant Ts : time :=) [0-9]*\.?[0-9]* ns;/\1 $CLK_PERIOD ns;/" "../tb/clk_gen.vhd"
clk_set=$(cat ../tb/clk_gen.vhd | grep "constant Ts : time :=" | cut -d ' ' -f 6)
if [ $CLK_PERIOD = $clk_set ]; then
	echo "clock period set correctly to: " $CLK_PERIOD " ns"
else
	echo "ERROR during change clock period"
fi
#open questasim and run script using the variable 'net'
vsim -c -do "do tb_verNetlist.do $net" > ../log/log_verifyNet_${line}.txt


cat tb_results.txt>>all_tb_results.txt
#check if the file generated by c code is different from results obtained by data_sink
./verifyResults.sh
done
